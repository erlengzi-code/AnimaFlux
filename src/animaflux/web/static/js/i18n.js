let _locale = "zh";
try {
  const saved = localStorage.getItem(KEY);
  if (saved === "zh" || saved === "en") _locale = saved;
} catch (_e) { /* localStorage 不可用时保持默认 */ }

const _listeners = new Set();

export function locale() {
  return _locale;
}

export function t(key, params) {
  const dict = STRINGS[_locale] || STRINGS.zh;
  let s = dict[key] ?? STRINGS.zh[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v ?? ""));
    }
  }
  return s;
}

export function setLocale(l) {
  if (l !== "zh" && l !== "en") return;
  _locale = l;
  try { localStorage.setItem(KEY, l); } catch (_e) { /* ignore */ }
  document.documentElement.lang = l === "zh" ? "zh-CN" : "en";
  _listeners.forEach((fn) => fn());
}

export function onLocaleChange(fn) {
  _listeners.add(fn);
  return () => _listeners.delete(fn);
}

// 固定枚举标签映射（前端展示，非模型数据翻译）。
export function vitalLabel(s) {
  if (!s) return "";
  return t(`vital.${String(s).toUpperCase()}`) || String(s);
}

export function stageLabel(s) {
  if (!s) return "—";
  const k = String(s).toLowerCase();
  return t(`stage.${k}`) || String(s);
}

